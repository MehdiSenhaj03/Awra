# Default legend: map letters to objects (x, y filled in). Per-level legends extend/override it.
BASE = {
    'S': {'t': 'safe'},
    'P': {'t': 'plate', 'ch': 1}, 'Q': {'t': 'plate', 'ch': 2}, 'R': {'t': 'plate', 'ch': 3},
    'D': {'t': 'door', 'k': 'chan', 'ch': 1}, 'F': {'t': 'door', 'k': 'chan', 'ch': 2}, 'G': {'t': 'door', 'k': 'chan', 'ch': 3},
    'M': {'t': 'door', 'k': 'door'},
    'B': {'t': 'button', 'ch': 1, 'dur': 180}, 'N': {'t': 'button', 'ch': 2, 'dur': 180},
    'L': {'t': 'lever', 'ch': 1}, 'l': {'t': 'lever', 'ch': 2},
    'V': {'t': 'vlever', 'ch': 5}, 'W': {'t': 'door', 'k': 'vault', 'ch': 5},
    'T': {'t': 'term', 'ch': 2, 'dur': 600},
    'K': {'t': 'door', 'k': 'key', 'color': 0}, 'k': {'t': 'card', 'color': 0},
    'J': {'t': 'door', 'k': 'key', 'color': 1}, 'j': {'t': 'card', 'color': 1},
    '*': {'t': 'gem'},
}

def L(lid, name, rows, loop=30, budget=2, par=1, legend=None, guards=(), darks=(), plans=(), story=None, extra=()):
    rows = [r for r in rows.strip('\n').split('\n')]
    w = max(len(r) for r in rows)
    h = len(rows)
    leg = dict(BASE)
    if legend:
        leg.update(legend)
    out_rows = []
    objs = []
    spawn = None
    for y, r in enumerate(rows):
        r = r.ljust(w, ' ')
        o = ''
        for x, c in enumerate(r):
            if c == '@':
                spawn = [x, y]
                o += '.'
            elif c in '#.gE ':
                o += c
            elif c in leg:
                d = dict(leg[c])
                d['x'] = x
                d['y'] = y
                objs.append(d)
                o += 'g' if d.get('glass') else '.'
            else:
                raise SystemExit(f'{lid}: unknown char {c!r} at {x},{y}')
        out_rows.append(o)
    for d in darks:
        objs.append(dict(d, t='dark'))
    for e in extra:
        objs.append(dict(e))
    assert spawn, lid
    data = {'v': 1, 'id': lid, 'name': name, 'author': 'Valmont', 'w': w, 'h': h, 'rows': out_rows, 'loop': int(loop * 60),
            'budget': budget, 'par': par, 'spawn': spawn, 'objs': objs, 'guards': [dict(g) for g in guards]}
    LEVELS.append((lid, data, [list(p) for p in plans]))

