#!/usr/bin/env python3
"""Generates bindings/rust/awra-sys/src/lib.rs from include/awra/awra.h:
every function prototype as an extern "C" declaration, enums as integer
constants, the public structs as #[repr(C)]."""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "include", "awra", "awra.h")).read()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)

TYPES = {
    "void": "()", "bool": "bool", "int": "c_int", "unsigned": "c_uint", "unsigned long": "c_ulong",
    "double": "f64", "float": "f32", "size_t": "usize", "uint64_t": "u64", "uint8_t": "u8",
    "uint32_t": "u32", "long long": "i64",
}
ENUMS = set(re.findall(r"typedef enum \{[^}]*\} (\w+);", src, re.S))
STRUCT_PTRS = {"AwraWidget", "AwraRGBA", "AwraArgs", "AwraMenuItem", "AwraCommand",
               "AwraFileFilter", "AwraCanvas", "AwraTexture", "AwraEmoji", "AwraIconPaintable"}
CALLBACKS = {
    "AwraHandler": "Option<unsafe extern \"C\" fn(*mut AwraWidget, *const AwraArgs, *mut c_void)>",
    "AwraDestroyNotify": "Option<unsafe extern \"C\" fn(*mut c_void)>",
    "AwraFileCallback": "Option<unsafe extern \"C\" fn(*const c_char, *mut c_void)>",
    "AwraDrawFunc": "Option<unsafe extern \"C\" fn(*mut AwraWidget, *mut AwraCanvas, c_int, c_int, *mut c_void)>",
    "AwraCollectionSetup": "Option<unsafe extern \"C\" fn(*mut AwraWidget, c_int, *mut c_void) -> *mut AwraWidget>",
    "AwraCollectionBind": "Option<unsafe extern \"C\" fn(*mut AwraWidget, *mut AwraWidget, c_int, c_int, *mut c_void)>",
    "AwraCollectionUnbind": "Option<unsafe extern \"C\" fn(*mut AwraWidget, *mut AwraWidget, c_int, c_int, *mut c_void)>",
    "AwraLayoutMeasureFunc": "Option<unsafe extern \"C\" fn(*mut AwraWidget, c_int, c_int, *mut c_int, *mut c_int, *mut c_void)>",
    "AwraLayoutAllocateFunc": "Option<unsafe extern \"C\" fn(*mut AwraWidget, c_int, c_int, *mut c_void)>",
    "AwraOverlayPositionFunc": "Option<unsafe extern \"C\" fn(*mut AwraWidget, *mut AwraWidget, *mut c_int, *mut c_int, *mut c_int, *mut c_int, *mut c_void) -> bool>",
    "AwraListItemFunc": "Option<unsafe extern \"C\" fn(*mut AwraWidget, *mut AwraWidget, *mut c_void)>",
}

def rtype(t):
    t = t.strip()
    if re.sub(r"\s+", "", t) == "constchar*const*":
        return "*const *const c_char"
    if re.sub(r"\s+", "", t) == "constchar*const**":
        return "*mut *const *const c_char"
    t = re.sub(r"\s+", " ", t)
    if t in CALLBACKS:
        return CALLBACKS[t]
    const = t.startswith("const ")
    if const:
        t = t[6:]
    stars = t.count("*")
    base = t.replace("*", "").replace("const", "").strip()
    if base == "char":
        r = "c_char"
    elif base == "void":
        r = "c_void" if stars else "()"
    elif base in TYPES:
        r = TYPES[base]
    elif base in ENUMS:
        r = "c_int"
    elif base in STRUCT_PTRS:
        r = base
    else:
        raise SystemExit("unknown type: " + t)
    for i in range(stars):
        inner_const = const if i == 0 else ("const" in t.split("*")[i] if "*" in t else False)
        r = ("*const " if (const and i == 0) else "*mut ") + r
    # const char *const * -> *const *const c_char
    if "const char *const *" in (("const " if const else "") + t + ("" )):
        r = "*const *const c_char"
    return r

def split_params(p):
    p = p.strip()
    if p in ("", "void"):
        return []
    out, depth, cur = [], 0, ""
    for ch in p:
        if ch == "(":
            depth += 1
        if ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return out

def param(p):
    p = p.strip()
    m = re.match(r"(.*\(\*(\w+)\)\s*\((.*)\))", p)
    if m:  # inline function pointer
        name = m.group(2)
        if name in ("fn", "type", "ref", "match", "loop", "move"):
            name += "_"
        ret = p[: p.index("(")].strip()
        def strip_name(a):
            a = a.strip()
            if "*" in a or len(a.split()) > 1:
                a2 = re.sub(r"[A-Za-z_]\w*$", "", a).strip()
                if a2 and a2 not in ("const", "unsigned"):
                    return a2
            return a
        args = [rtype(strip_name(a)) for a in split_params(m.group(3))]
        return name, "Option<unsafe extern \"C\" fn(%s)%s>" % (", ".join(args), "" if rtype(ret) == "()" else " -> " + rtype(ret))
    m = re.match(r"(.*?)(\w+)$", p)
    typ, name = m.group(1), m.group(2)
    if name in ("type", "match", "ref", "fn", "loop", "move", "box", "impl", "self"):
        name = name + "_"
    return name, rtype(typ)

out = ['//! Raw FFI to Awra 2 (generated by tools/gen_rust_sys.py from include/awra/awra.h).',
       '//! SPDX-License-Identifier: GPL-3.0-or-later',
       '#![allow(non_camel_case_types, non_upper_case_globals, clippy::all)]',
       'use std::os::raw::{c_char, c_int, c_uint, c_ulong, c_void};', '',
       '#[repr(C)] pub struct AwraWidget { _p: [u8; 0] }',
       '#[repr(C)] pub struct AwraCanvas { _p: [u8; 0] }',
       '#[repr(C)] pub struct AwraTexture { _p: [u8; 0] }',
       '#[repr(C)] pub struct AwraIconPaintable { _p: [u8; 0] }',
       '#[repr(C)] #[derive(Clone, Copy)] pub struct AwraEmoji { pub id: *const c_char, pub name: *const c_char, pub text: *const c_char, pub texture: *mut AwraTexture, pub keywords: *const c_char }',
       '#[repr(C)] #[derive(Clone, Copy, Debug, Default, PartialEq)] pub struct AwraRGBA { pub r: f32, pub g: f32, pub b: f32, pub a: f32 }',
       '#[repr(C)] #[derive(Clone, Copy)] pub struct AwraArgs { pub signal: c_int, pub active: bool, pub value: f64, pub index: c_int, pub text: *const c_char, pub x: f64, pub y: f64, pub dx: f64, pub dy: f64, pub button: c_int, pub n_press: c_int, pub mods: c_int, pub keysym: *const c_char, pub width: c_int, pub height: c_int, pub handled: *mut bool, pub code: *const c_char }',
       '#[repr(C)] #[derive(Clone, Copy)] pub struct AwraMenuItem { pub label: *const c_char, pub icon_name: *const c_char, pub accel: *const c_char, pub check: c_int, pub sensitive: bool, pub destructive: bool, pub handler: Option<unsafe extern "C" fn(*mut AwraWidget, *const AwraArgs, *mut c_void)>, pub data: *mut c_void }',
       '#[repr(C)] #[derive(Clone, Copy)] pub struct AwraCommand { pub title: *const c_char, pub subtitle: *const c_char, pub icon_name: *const c_char, pub accel: *const c_char, pub section: *const c_char }',
       '#[repr(C)] #[derive(Clone, Copy)] pub struct AwraFileFilter { pub name: *const c_char, pub patterns: *const c_char }',
       '']
# enum constants
for body, name in re.findall(r"typedef enum \{([^}]*)\} (\w+);", src, re.S):
    val = -1
    for item in body.split(","):
        item = item.strip()
        if not item:
            continue
        if "=" in item:
            k, v = [x.strip() for x in item.split("=", 1)]
            try:
                val = int(v, 0)
            except ValueError:
                if "<<" in v:
                    a, b = v.split("<<")
                    val = int(a) << int(b)
                else:
                    out.append("pub const %s: c_int = %s;" % (k, v))
                    continue
        else:
            k = item
            val += 1
        out.append("pub const %s: c_int = %d;" % (k, val))
for body in re.findall(r"\nenum \{([^}]*)\};", src, re.S):
    for item in body.split(","):
        item = item.strip()
        if "=" in item:
            k, v = [x.strip() for x in item.split("=", 1)]
            out.append("pub const %s: c_int = %s;" % (k, v))
out.append("")
out.append('extern "C" {')
decls = re.findall(r"\n((?:const )?[\w ]+?\s*(?:\*\s*(?:const\s*)?)*)\s*(awra_\w+)\s*\(([^;]*?)\)\s*;", src, re.S)
seen = set()
for ret, name, params in decls:
    if name in seen:
        continue
    seen.add(name)
    params = re.sub(r"\s+", " ", params)
    args = [param(p) for p in split_params(params)]
    r = rtype(ret)
    out.append("    pub fn %s(%s)%s;" % (name, ", ".join("%s: %s" % a for a in args), "" if r == "()" else " -> " + r))
out.append("}")
open(os.path.join(ROOT, "bindings", "rust", "awra-sys", "src", "lib.rs"), "w").write("\n".join(out) + "\n")
print(len(seen), "functions")
