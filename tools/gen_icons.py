#!/usr/bin/env python3
"""Generates src/icons-data.c: the symbolic icons Awra ships, as minified SVG.

Sources: resources/icons (Awra's own) and the Adwaita icon theme's symbolic
icons (CC-BY-SA-3.0 / LGPL-3.0, see LICENSES/), found under ADWAITA_DIR or
/usr/share/icons/Adwaita/symbolic. Usage: tools/gen_icons.py [names...]
"""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADW = os.environ.get("ADWAITA_DIR", "/usr/share/icons/Adwaita/symbolic")
NAMES = open(os.path.join(ROOT, "tools", "icons.txt")).read().split()

def find(name):
    own = os.path.join(ROOT, "resources", "icons", name + ".svg")
    if os.path.exists(own):
        return own
    hits = glob.glob(os.path.join(ADW, "*", name + ".svg"))
    return hits[0] if hits else None

def minify(svg):
    svg = re.sub(r"<\?xml.*?\?>", "", svg, flags=re.S)
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r"<metadata.*?</metadata>", "", svg, flags=re.S)
    svg = re.sub(r"<title>.*?</title>", "", svg, flags=re.S)
    svg = re.sub(r"\s+", " ", svg)
    svg = re.sub(r">\s+<", "><", svg)
    return svg.strip()

out = ["/* Generated by tools/gen_icons.py: do not edit.",
       " * Awra's icons (resources/icons) and Adwaita's symbolic icons",
       " * (CC-BY-SA-3.0 / LGPL-3.0-or-later, the GNOME Project). */",
       "#include <stddef.h>",
       "typedef struct AwraIconSource { const char *name; const char *svg; } AwraIconSource;",
       "const AwraIconSource awra_icon_sources[] = {"]
missing = []
for n in sorted(set(NAMES)):
    p = find(n)
    if not p:
        missing.append(n)
        continue
    s = minify(open(p, encoding="utf-8").read())
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    out.append('  {"%s", "%s"},' % (n, s))
out.append("  {NULL, NULL}};")
open(os.path.join(ROOT, "src", "icons-data.c"), "w").write("\n".join(out) + "\n")
if missing:
    print("missing:", " ".join(missing), file=sys.stderr)
