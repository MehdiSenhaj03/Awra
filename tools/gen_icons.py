#!/usr/bin/env python3
"""Generates src/icons-data.c: the icons Awra builds in (src/icontheme.h).

- "gtk": GTK's resource icons (/org/gtk/libgtk/icons, LGPL-2.1-or-later):
  its symbolic SVGs, unthemed, and hicolor's 16x16/status/image-missing.png,
  from GTK_ICONS_DIR (a GTK 4.22 checkout's gtk/icons, default
  /opt/src/gtk/gtk/icons), with GTK's hicolor.index.theme.
- "awra": Awra's own (resources/icons, as Awra 1's /org/awra/icons).
- "adwaita": Adwaita's symbolic icons (CC-BY-SA-3.0 / LGPL-3.0-or-later, the
  GNOME Project) named in tools/icons.txt, their right-to-left variants, under
  their theme directories, with an index.theme for them: the "Adwaita" theme
  of systems that have none (ADWAITA_DIR, default /usr/share/icons/Adwaita).

The files are kept as they are (GTK reads symbolic SVGs strictly: dropping
an element would change how it draws them), the XML declaration, comments
and blank runs between tags aside. Usage: tools/gen_icons.py
"""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GTK = os.environ.get("GTK_ICONS_DIR", "/opt/src/gtk/gtk/icons")
ADW = os.environ.get("ADWAITA_DIR", "/usr/share/icons/Adwaita")
NAMES = open(os.path.join(ROOT, "tools", "icons.txt")).read().split()


def strip(svg):
    svg = re.sub(r"<\?xml.*?\?>", "", svg, flags=re.S)
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r">\s+<", "><", svg)
    return svg.strip()


def c_bytes(data):
    out = []
    line = ""
    for b in data:
        if b == 0x22:
            s = '\\"'
        elif b == 0x5C:
            s = "\\\\"
        elif 0x20 <= b < 0x7F and b != 0x3F:  # no trigraphs
            s = chr(b)
        else:
            s = "\\%03o" % b
        line += s
        if len(line) > 100:
            out.append('"%s"' % line)
            line = ""
    if line or not out:
        out.append('"%s"' % line)
    return "\n    ".join(out)


def svg_entry(path, file):
    return (path, strip(open(file, encoding="utf-8").read()).encode("utf-8"))


sets = {}

# GTK's
gtk = []
for f in sorted(glob.glob(os.path.join(GTK, "*.svg"))):
    gtk.append(svg_entry(os.path.basename(f), f))
png = os.path.join(GTK, "16x16", "status", "image-missing.png")
gtk.append(("16x16/status/image-missing.png", open(png, "rb").read()))
sets["gtk"] = gtk
hicolor_index = open(os.path.join(GTK, "hicolor.index.theme"), encoding="utf-8").read()
hicolor_index = "\n".join(l for l in hicolor_index.splitlines()
                          if l.strip() and not l.startswith("Context="))

# Awra's (Awra 1's /org/awra/icons)
awra = []
for f in sorted(glob.glob(os.path.join(ROOT, "resources", "icons", "*.svg"))):
    awra.append(svg_entry(os.path.basename(f), f))
sets["awra"] = awra

# Adwaita's symbolic icons, where Adwaita keeps them
own = {os.path.basename(p)[:-4] for p in glob.glob(os.path.join(ROOT, "resources", "icons", "*.svg"))}
adw = []
dirs = set()
missing = []
for n in sorted(set(NAMES)):
    if n in own:
        continue
    hits = sorted(glob.glob(os.path.join(ADW, "symbolic*", "*", n + ".svg")))
    if not hits:
        missing.append(n)
        continue
    for h in hits[:1] + sorted(glob.glob(os.path.join(os.path.dirname(hits[0]), n + "-rtl.svg"))):
        rel = os.path.relpath(h, ADW).replace(os.sep, "/")
        dirs.add(os.path.dirname(rel))
        adw.append(svg_entry(rel, h))
sets["adwaita"] = sorted(adw)
index = open(os.path.join(ADW, "index.theme"), encoding="utf-8").read()
groups = re.split(r"\n(?=\[)", index)
keep = ["[Icon Theme]\nName=Adwaita\nInherits=hicolor\nDirectories=" + ",".join(sorted(dirs))]
for g in groups:
    m = re.match(r"\[(.*?)\]", g)
    if m and m.group(1) in dirs:
        keep.append("\n".join(l for l in g.strip().splitlines() if not l.startswith("Context=")))
adwaita_index = "\n".join(dict.fromkeys(keep))

out = ["/* Generated by tools/gen_icons.py: do not edit.",
       " * GTK's resource icons (LGPL-2.1-or-later, the GTK team), Awra's icons",
       " * (resources/icons) and Adwaita's symbolic icons (CC-BY-SA-3.0 /",
       " * LGPL-3.0-or-later, the GNOME Project). */",
       '#include "icontheme.h"',
       ""]
for name, entries in sets.items():
    entries = sorted(entries)
    out.append("static const AwraBuiltinIcon %s_icons[] = {" % name)
    for path, data in entries:
        out.append('  {"%s", (const unsigned char *)\n    %s,\n    %d},' % (path, c_bytes(data), len(data)))
    out.append("};")
    out.append('const AwraBuiltinSet awra_builtin_%s = {"%s", %s_icons, %d};' % (name, name, name, len(entries)))
    out.append("")
out.append("const char awra_builtin_hicolor_index[] =\n    %s;" % c_bytes(hicolor_index.encode()))
out.append("const char awra_builtin_adwaita_index[] =\n    %s;" % c_bytes(adwaita_index.encode()))
open(os.path.join(ROOT, "src", "icons-data.c"), "w").write("\n".join(out) + "\n")
if missing:
    print("missing:", " ".join(missing), file=sys.stderr)
